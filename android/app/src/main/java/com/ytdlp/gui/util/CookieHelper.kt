package com.ytdlp.gui.util

import android.content.Context
import android.webkit.CookieManager
import java.io.File

object CookieHelper {
    
    private const val COOKIES_FILENAME = "cookies.txt"
    
    fun getCookiesFile(context: Context): File {
        return File(context.filesDir, COOKIES_FILENAME)
    }
    
    fun hasCookies(context: Context): Boolean {
        val file = getCookiesFile(context)
        return file.exists() && file.length() > 0
    }
    
    fun saveCookies(context: Context, cookies: String) {
        val file = getCookiesFile(context)
        file.writeText(cookies)
    }
    
    fun deleteCookies(context: Context) {
        val file = getCookiesFile(context)
        if (file.exists()) {
            file.delete()
        }
    }
    
    fun convertToNetscapeCookies(domain: String, cookies: String): String {
        val sb = StringBuilder()
        sb.appendLine("# Netscape HTTP Cookie File")
        sb.appendLine("# This file was generated by YT-DLP GUI for Android")
        sb.appendLine()
        
        cookies.split(";").forEach { cookie ->
            val parts = cookie.trim().split("=", limit = 2)
            if (parts.size == 2) {
                val name = parts[0].trim()
                val value = parts[1].trim()
                
                // Formato Netscape: domain, flag, path, secure, expiry, name, value
                // .youtube.com	TRUE	/	TRUE	0	NAME	VALUE
                val domainEntry = if (domain.startsWith(".")) domain else ".$domain"
                sb.appendLine("$domainEntry\tTRUE\t/\tTRUE\t0\t$name\t$value")
            }
        }
        
        return sb.toString()
    }
    
    fun getYouTubeCookies(): String? {
        return CookieManager.getInstance().getCookie("https://www.youtube.com")
    }
    
    fun getGoogleCookies(): String? {
        return CookieManager.getInstance().getCookie("https://accounts.google.com")
    }
    
    fun clearWebViewCookies() {
        CookieManager.getInstance().removeAllCookies(null)
        CookieManager.getInstance().flush()
    }
    
    fun isLoggedIn(): Boolean {
        val cookies = getYouTubeCookies() ?: return false
        return cookies.contains("SID=") || 
               cookies.contains("SSID=") ||
               cookies.contains("LOGIN_INFO=")
    }
}
